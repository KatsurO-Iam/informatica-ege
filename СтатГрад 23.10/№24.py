with open("24.txt") as f:
    sp = f.readline()

reg = compile(r"\d+(?:[*+]\d+)*")
max_len = -float('inf')
res = []
for x in reg.finditer(sp):
    if (x[0].count('+') + x[0].count('*')) < 50:
        res.append([len(x[0]), x[0]])
        continue
    for l in range(len(x[0])):
        for r in range(l + 1, len(x[0])):
            if (x[0][l:r+1].count('+') + x[0][l:r+1].count('*')) < 50:
                res.append([(r + 1 - l), x[0][l:r+1]])
            else:
                break
print(max(res))
